#!/usr/bin/env node
/**
 * Regenerate the View Lab registry totals in `scripts/README.md`.
 *
 * The counts live in the registry; this owns the one region of prose that states them, and
 * `tests/view-lab-cases.test.js` holds the committed region to what {@link totalsRegion} emits, so
 * the gate is that test and this is only the local regenerator.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { registryTotals } from './lib/viewLabCases.js';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const REGION_START = '<!-- viewlab-totals:start -->';
const REGION_END = '<!-- viewlab-totals:end -->';

/** The document that carries the region, as a diff names it. */
// eslint-disable-next-line unicorn/no-exports-in-scripts -- dual-mode CLI, imported by tests.
export const TOTALS_DOCUMENT = 'scripts/README.md';

/**
 * The region as the registry says it should read, delimiters included and one sentence per line,
 * because `lint:md` enforces that over the document it lands in.
 *
 * @param {ReturnType<typeof registryTotals>} [totals]
 * @returns {string}
 */
// eslint-disable-next-line unicorn/no-exports-in-scripts -- dual-mode CLI, imported by tests.
export function totalsRegion(totals = registryTotals()) {
  return [
    REGION_START,
    `The registry holds ${totals.total} publishable cases: ${totals.exact} \`exact\`, ` +
      `${totals.window} \`window\`, and ${totals.beyond} \`beyond\`.`,
    `Surface coverage — one frame of every route and tab the lab renders — is ` +
      `${totals.coverage} of them.`,
    'These counts are generated by `npm run viewlab:totals`; change a case file, not this region.',
    REGION_END,
  ].join('\n');
}

/** The document with its one region replaced; a missing, inverted or duplicated region throws. */
// eslint-disable-next-line unicorn/no-exports-in-scripts -- dual-mode CLI, imported by tests.
export function withTotalsRegion(markdown, region = totalsRegion()) {
  const start = markdown.indexOf(REGION_START);
  const end = markdown.indexOf(REGION_END);
  // Splicing on a missing or inverted delimiter would drop the surrounding prose silently.
  if (start === -1 || end < start) {
    throw new Error(`${TOTALS_DOCUMENT} has no ${REGION_START} … ${REGION_END} region`);
  }
  // A second region would keep stale counts behind a fresh first one.
  if (markdown.includes(REGION_START, start + 1) || markdown.includes(REGION_END, end + 1)) {
    throw new Error(`${TOTALS_DOCUMENT} has more than one ${REGION_START} … ${REGION_END} region`);
  }
  return markdown.slice(0, start) + region + markdown.slice(end + REGION_END.length);
}

function main() {
  const target = resolve(ROOT, TOTALS_DOCUMENT);
  const before = readFileSync(target, 'utf8');
  const after = withTotalsRegion(before);
  if (after === before) {
    console.log(`${TOTALS_DOCUMENT}: totals region already current`);
    return 0;
  }
  writeFileSync(target, after);
  console.log(`${TOTALS_DOCUMENT}: totals region rewritten`);
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.exitCode = main();
}
