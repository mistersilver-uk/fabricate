/**
 * The sweep alphabet: digits, the decimal point, the five operators, both parentheses, a path, a
 * function name, a dice term and a space. Every sequence of one to four tokens is a source.
 */
export const SWEEP_TOKENS = Object.freeze([
  '1',
  '2',
  '.',
  '+',
  '-',
  '*',
  '/',
  '%',
  '(',
  ')',
  '@a',
  'floor',
  'd6',
  ' ',
]);

export const SWEEP_MAX_LENGTH = 4;

/** The roll data every sweep source resolves against. */
export const SWEEP_ROLL_DATA_NAME = 'sweep-a';

/** Yields every sweep source in a fixed order: by length, then lexicographically by token index. */
export function* sweepSources() {
  const count = SWEEP_TOKENS.length;
  for (let length = 1; length <= SWEEP_MAX_LENGTH; length += 1) {
    const cursor = Array.from({ length }, () => 0);
    for (;;) {
      yield cursor.map((index) => SWEEP_TOKENS[index]).join('');
      let place = length - 1;
      while (place >= 0 && cursor[place] === count - 1) {
        cursor[place] = 0;
        place -= 1;
      }
      if (place < 0) break;
      cursor[place] += 1;
    }
  }
}
